// One-off: download the brand fonts from Google Fonts as self-hosted WOFF2
// (Latin + Latin-Ext only) and write src/styles/fonts.css. Run: node scripts/fetch-fonts.mjs
import { writeFile, mkdir } from 'node:fs/promises';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,400..700;1,9..144,400..600&family=Inter:wght@400..700&family=JetBrains+Mono:wght@400;500&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36';
const SUBSETS = new Set(['latin', 'latin-ext']);

const css = await (await fetch(CSS_URL, { headers: { 'user-agent': UA } })).text();
const faces = new Map(); // file name -> face

for (const [, subset, body] of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face\s*{([^}]*)}/g)) {
  if (!SUBSETS.has(subset)) continue;
  const get = (prop) => new RegExp(`${prop}:\\s*([^;]+);`).exec(body)?.[1].trim();
  const family = get('font-family').replace(/'/g, '');
  const style = get('font-style');
  const weights = get('font-weight').split(/\s+/).map(Number);
  const url = /url\(([^)]+)\)/.exec(get('src'))[1];
  const name = `${family.toLowerCase().replace(/\s+/g, '-')}${style === 'italic' ? '-italic' : ''}-${subset}`;
  const face = faces.get(name) ?? { family, style, subset, url, min: Infinity, max: -Infinity, range: get('unicode-range') };
  face.min = Math.min(face.min, ...weights);
  face.max = Math.max(face.max, ...weights);
  faces.set(name, face);
}

await mkdir('src/static/fonts', { recursive: true });
let out = '/* Self-hosted brand fonts (Google Fonts, OFL). Generated by scripts/fetch-fonts.mjs. */\n';
for (const [name, f] of faces) {
  const buf = Buffer.from(await (await fetch(f.url, { headers: { 'user-agent': UA } })).arrayBuffer());
  await writeFile(`src/static/fonts/${name}.woff2`, buf);
  const weight = f.min === f.max ? `${f.min}` : `${f.min} ${f.max}`;
  out += `@font-face {
  font-family: "${f.family}";
  font-style: ${f.style};
  font-weight: ${weight};
  font-display: swap;
  src: url(/fonts/${name}.woff2) format("woff2");
  unicode-range: ${f.range};
}
`;
  console.log(`${name}.woff2 ${(buf.length / 1024).toFixed(0)} KB`);
}
await writeFile('src/styles/fonts.css', out);
